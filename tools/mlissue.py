#!/usr/bin/env python3
"""Issue and task helpers that must not drift: ids and titles, the generated at-a-glance block, the close gate.

  python3 tools/mlissue.py title ISSUE-001 T-005 "Heat exchanger pressure drop"   # [ISSUE-001][T-005] Heat exchanger ...
  python3 tools/mlissue.py label ISSUE-001                                         # issue-001
  python3 tools/mlissue.py summary docs/issues/ISSUE-001.md [--write | --check]
  python3 tools/mlissue.py check docs/issues/ISSUE-001.md                          # FAIL blocks saving, WARN goes to Open items
  python3 tools/mlissue.py task docs/issues/ISSUE-001.md T-001 "Pressure drop" [--builds-on T-000] [--write]   # task body + header slice from the issue
  python3 tools/mlissue.py answers ISSUE-001 [--dir docs/issues]                   # the tasks' Answers, to build the conclusion from
  python3 tools/mlissue.py history ISSUE-002 [--dir docs/issues]                   # every attempt ISSUE-002 follows, derived from the files
  python3 tools/mlissue.py can-close ISSUE-001 [--dir docs/issues]
  python3 tools/mlissue.py can-merge ISSUE-001 [--dir docs/issues]                 # closable, Outcome met, no task awaiting approval

The id formats live in .modelica-skills/config.yml under `ids` (defaults below). The at-a-glance block between
the markers is generated from the machine-read header, so the readable summary cannot disagree with it.
"""
import argparse, re, sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from evals.mlgates.spec import load_spec, read_text  # noqa: E402
from evals.mlgates.static import _exceeds  # noqa: E402

TOLERANCE_GATES = ("G3", "G6a")  # gates whose pass/fail needs a declared tolerance

IDS = {"issue": "ISSUE-{n:03d}", "task": "T-{n:03d}", "title": "[{issue}][{task}] {title}", "label": "{issue_lower}"}
BEGIN = "<!-- summary:begin (generated by tools/mlissue.py from the header; edit the header, not this block) -->"
END = "<!-- summary:end -->"
TEMPLATE = Path(__file__).resolve().parents[1] / "templates" / "task.md"
# keys a task needs to be built, run and compared with no other context
SLICE = ("level", "model_files", "boundary_conditions", "initial_conditions", "reference_state", "feasibility",
         "fragile_spots", "acceptance", "baseline", "envelope", "tolerances", "sources")
CONCLUSION_HEADINGS = ("## Answer", "## Results", "## Deviations", "## Accepted gaps", "## Open items", "## Out of scope")
TASK_STATUS = ("ready-for-agent", "awaiting-approval")  # a task with no status is not released to an agent yet
SUFFIXES = ("-conclusion.md", "-failure.md")  # files next to an issue that are not issues
# hypothesis lines: "H2 [open] text" in a failure note; "ISSUE-001:H2 ruled-out evidence: ..." in a later conclusion
HYP = re.compile(r"^\W*(H\d+)\s*\[(open|ruled-out|confirmed)\]\s*(.*)", re.M)
TESTED = re.compile(r"^\W*([\w-]+:H\d+)\s+(open|ruled-out|confirmed)\b(.*)", re.M)


def task_title(issue, task, title, fmt=None):
    return (fmt or IDS["title"]).format(issue=issue, task=task, title=title.strip())


def label(issue, fmt=None):
    return (fmt or IDS["label"]).format(issue=issue, issue_lower=issue.lower())


def _fmt(x):
    return "–" if x is None else f"{x:g}" if isinstance(x, (int, float)) else str(x)


def _table(head, rows):
    if not rows:
        return ""
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    out += ["| " + " | ".join(str(c).replace("|", "\\|") for c in r) + " |" for r in rows]
    return "\n".join(out)


def issue_file(issues_dir, issue_id):
    d = Path(issues_dir)
    if (d / f"{issue_id}.md").exists():
        return d / f"{issue_id}.md"
    return next((p for p in sorted(d.glob(f"{issue_id}*.md")) if not p.name.endswith(SUFFIXES)), None) if d.is_dir() else None


def _answer_outcome(text):
    """('met'|'missed'|None, rest of the line) from the Outcome line of the Answer section; the template placeholder gives None."""
    for ln in _section(text, "Answer").splitlines():
        m = re.search(r"outcome\W*\s*(met|missed)\b(?!\s*\|)(.*)", ln, flags=re.I)
        if m:
            return m.group(1).lower(), m.group(2).strip(" *,:;—-")
    return None, ""


def outcome(issues_dir, issue_id):
    c = Path(issues_dir) / f"{issue_id}-conclusion.md"
    return _answer_outcome(read_text(c)) if c.exists() else (None, "")


def ancestors(spec, issues_dir):
    """[(id, path, spec)] of the issues this one follows, oldest first. Stops at a missing file or a loop."""
    out, seen, nxt = [], {spec.get("id")}, spec.get("follows")
    while nxt and nxt not in seen:
        seen.add(nxt)
        p = issue_file(issues_dir, nxt)
        try:
            s = load_spec(p) if p else None
        except Exception:  # unparseable ancestor: the chain ends there, check() reports the header
            s = None
        if s is None:
            break
        out.append((nxt, p, s))
        nxt = s.get("follows")
    return out[::-1]


def history_block(spec, issues_dir):
    """Table of every attempt this issue follows, with the latest status of each hypothesis. Derived, never typed."""
    d, rows, hyps = Path(issues_dir), [], {}
    for iid, _, s in ancestors(spec, d):
        c, f = d / f"{iid}-conclusion.md", d / f"{iid}-failure.md"
        ctext = read_text(c) if c.exists() else ""
        ftext = read_text(f) if f.exists() else ""
        for k, st, _ in TESTED.findall(_section(ctext, "Hypotheses tested")):
            if k in hyps:
                hyps[k] = (st, hyps[k][1])
        for h, st, txt in HYP.findall(_section(ftext, "Hypotheses")):
            hyps[f"{iid}:{h}"] = (st, txt.strip())
        o, rest = _answer_outcome(ctext)
        first = lambda t, h: (_section(t, h).splitlines() or ["–"])[0]
        rows.append((iid, s.get("title", "–"), f"{o or '–'}, {rest}" if rest else o or "–", first(ftext, "Cause bucket"), first(ftext, "Decision")))
    if not rows:
        return ""
    out = "**History** (every attempt this issue follows, oldest first)\n\n" + _table(["Issue", "Attempt", "Outcome", "Cause", "Decision"], rows)
    if hyps:
        out += "\n\n" + _table(["Hypothesis", "Status", "Text"], [(k, v[0], v[1]) for k, v in hyps.items()])
    return out


def summary_block(spec, issues_dir=None):
    parts =[f"**Level {spec.get('level')}.** Decision: {spec.get('decision', 'TO-VERIFY')}"]
    lst = lambda k: "; ".join(map(str, spec.get(k) or [])) or "none"
    ref = spec.get("reference_state") or {}
    parts.append("**Conditions**\n\n" + _table(["Item", "Value"], [
        ("Boundary", lst("boundary_conditions")), ("Initial", lst("initial_conditions")),
        ("Reference state", f"{ref.get('id', '–')} ({ref.get('medium', '–')})"),
        ("Fragile spots", lst("fragile_spots"))]))
    feas = spec.get("feasibility") or []
    if feas:
        parts.append("**Feasibility**\n\n" + _table(["Target", "Ideal limit", "Reachable"],
                     [(f.get("target"), f.get("ideal_limit"), f.get("reachable")) for f in feas]))
    dl = spec.get("deliverables") or []
    if dl:
        parts.append("**Deliverables**\n\n" + _table(["Result", "Proven by"], [(d.get("result"), d.get("gate")) for d in dl]))
    acc = spec.get("acceptance") or []
    if acc:
        parts.append("**Acceptance**\n\n" + _table(["Metric", "Target", "Unit", "Against"],
                     [(a.get("metric"), _fmt(a.get("target")), a.get("unit", "–"), a.get("against", "–")) for a in acc]))
    b = spec.get("baseline")
    if b:
        parts.append(f"**Baseline** (follows {spec.get('follows')}): {b.get('metric')} = {_fmt(b.get('value'))}, target {_fmt(b.get('target'))}")
    env = spec.get("envelope") or []
    parts.append("**Ranges**\n\n" + (_table(["Variable", "Unit", "Min", "Max", "Guard min", "Guard max"],
                 [(e["var"], e.get("unit", "–"), _fmt(e.get("min")), _fmt(e.get("max")), _fmt(e.get("guard_min")),
                   _fmt(e.get("guard_max"))) for e in env]) or "none declared"))
    tol = spec.get("tolerances") or {}
    gates = (spec.get("verification") or {}).get("gates") or []
    ref = (spec.get("verification") or {}).get("reference", "–")
    rows = []
    for g in gates:
        mine = {k: v for k, v in tol.items() if k.startswith(g + "_")}
        rows.append((g, ", ".join(f"{k[len(g) + 1:]} = {_fmt(v)}" for k, v in mine.items()) or "–",
                     ref if g == "G6a" else "–"))
    parts.append("**Checks**\n\n" + (_table(["Check", "Tolerance", "Reference"], rows) or "none declared"))
    src = spec.get("sources") or []
    parts.append("**Sources**\n\n" + (_table(["Key", "Used for", "Locator", "Valid for", "Transcription"],
                 [(s["key"], s.get("used_for", "–"), s.get("locator", "–"),
                   "; ".join(f"{v['var']} [{_fmt(v.get('min'))}, {_fmt(v.get('max'))}]" for v in s.get("validity") or []) or "–",
                   s.get("transcription", "–")) for s in src]) or "none"))
    gaps = spec.get("accepted_gaps") or []
    if gaps:
        parts.append("**Accepted gaps (level L0)**\n\n" + _table(["Gate", "Owner", "Date", "Reason"],
                     [(g.get("gate"), g.get("owner"), g.get("date", "–"), g.get("reason")) for g in gaps]))
    hist = history_block(spec, issues_dir) if issues_dir and spec.get("follows") else ""
    if hist:
        parts.append(hist)
    return BEGIN + "\n\n" + "\n\n".join(parts) + "\n\n" + END


def _replace(text, block):
    m = re.search(re.escape(BEGIN.split(" (")[0]) + r".*?" + re.escape(END), text, flags=re.S)
    return None if not m else text[: m.start()] + block + text[m.end():]


def branch_problems(spec, issues_dir):
    """One branch per issue (ADR-0023): named after the issue, started from main or from the issue it was found in."""
    out, iid = [], str(spec.get("id"))
    exists = lambda i: bool(i) and issue_file(issues_dir, str(i)) is not None
    if spec.get("branch") and not str(spec["branch"]).startswith(label(iid) + "-"):
        out.append(f"branch {spec['branch']!r} must start with {label(iid)}- (one branch per issue)")
    base = spec.get("base")
    if base and base != "main" and (base == iid or not exists(base)):
        out.append(f"base {base} is neither main nor another issue in {issues_dir}")
    found = spec.get("discovered_from")
    if found and not exists(found):
        out.append(f"discovered_from {found}: no such issue in {issues_dir}")
    elif found and base != found:
        out.append(f"discovered_from {found} needs base {found}: the new branch starts from that issue's latest commit")
    if spec.get("paused_for") and not exists(spec["paused_for"]):
        out.append(f"paused_for {spec['paused_for']}: no such issue in {issues_dir}")
    return out


def check(path):
    """(failures, warnings). Failures block saving; warnings must be listed under Open items."""
    fails, warns = [], []
    try:
        spec = load_spec(path)
    except Exception as e:  # header unparseable
        return [f"header does not parse: {e}"], []
    if "issue" in spec:  # a task file: only its status is checked here
        st = spec.get("status")
        return ([f"status {st!r} is not one of {', '.join(TASK_STATUS)}"] if st and st not in TASK_STATUS else []), []
    fails += branch_problems(spec, Path(path).parent)
    env = {e["var"]: e for e in spec.get("envelope") or []}
    for s in spec.get("sources") or []:
        for v in s.get("validity") or []:
            if v["var"] in env and _exceeds(env[v["var"]], v) and not s.get("extrapolation_adr"):
                fails.append(f"{s['key']}: envelope of {v['var']} exceeds validity and no extrapolation_adr")
        if str(s.get("locator", "")).strip() in ("", "TO-VERIFY"):
            warns.append(f"{s['key']}: locator TO-VERIFY")
    gates = (spec.get("verification") or {}).get("gates") or []
    tol = spec.get("tolerances") or {}
    fails += [f"{g}: no tolerance declared" for g in gates if g in TOLERANCE_GATES and not any(k.startswith(g + "_") for k in tol)]
    fails += [f"deliverable {d.get('result')!r} names gate {d.get('gate')} not in verification.gates"
              for d in spec.get("deliverables") or [] if d.get("gate") not in gates]
    warns += [f"target {f.get('target')!r} not reachable (ideal limit {f.get('ideal_limit')})"
              for f in spec.get("feasibility") or [] if f.get("reachable") is not True]
    d = Path(path).parent
    if (spec.get("verification") or {}).get("reference") and not spec.get("acceptance"):
        warns.append("no acceptance declared ({metric, target, unit, against}): a miss cannot be judged")
    if spec.get("follows"):
        if not issue_file(d, spec["follows"]):
            fails.append(f"follows {spec['follows']}: no such issue in {d}")
        elif outcome(d, spec["follows"])[0] != "missed":
            fails.append(f"follows {spec['follows']}: its conclusion does not say Outcome: missed")
        bl = spec.get("baseline") or {}
        fails += [f"baseline.{k} missing" for k in ("metric", "value", "target") if bl.get(k) is None]
    c = d / f"{spec.get('id')}-conclusion.md"
    if c.exists():
        for k, st, rest in TESTED.findall(_section(read_text(c), "Hypotheses tested")):
            if st != "open" and "evidence" not in rest.lower():
                warns.append(f"{k} marked {st} without evidence (cite the result that shows it)")
    text = read_text(path)
    if _replace(text, summary_block(spec, d)) != text:
        fails.append("summary block is stale: run `summary --write`")
    return fails, warns


def task_text(spec, task_id, title, builds_on=None, prev_answer=""):
    _, fm, body = read_text(TEMPLATE).split("---", 2)
    head = yaml.safe_load(fm)
    head.update(id=task_id, issue=spec["id"], title=task_title(spec["id"], task_id, title))
    if builds_on:
        head.update(builds_on=builds_on, blocked_by=[builds_on])
        quoted = "\n".join("> " + ln for ln in (prev_answer or "(no Answer yet)").splitlines())
        body = body.replace("## Model\n", f"## Model\nExtends the model files of the header as left by {builds_on}. Its Answer, credibility included:\n\n{quoted}\n\n", 1)
    head.update({k: spec[k] for k in SLICE if k in spec})
    ref = (spec.get("verification") or {}).get("reference")
    if ref:
        head["reference"] = ref
    body = body.replace("# <one physical question, answered end to end>", f"# {title.strip()}")
    return "---\n" + yaml.safe_dump(head, sort_keys=False, allow_unicode=True) + "---" + body


def _section(text, heading):
    m = re.search(rf"^##\s+{re.escape(heading)}[^\n]*\n(.*?)(?=^##\s|\Z)", text, flags=re.S | re.M)
    return m.group(1).strip() if m else ""


def task_answers(issue_id, tasks_dir):
    """[(task id, file, Answer text)] for the task files of this issue."""
    out = []
    for p in sorted(Path(tasks_dir).glob("*.md")) if Path(tasks_dir).is_dir() else []:
        text = read_text(p)
        try:
            fm = yaml.safe_load(text.split("---", 2)[1]) or {}
        except (IndexError, yaml.YAMLError):
            continue
        if isinstance(fm, dict) and str(fm.get("issue")) == issue_id:
            out.append((str(fm.get("id") or p.stem), p, _section(text, "Answer")))
    return out


def can_close(issue_id, directory="docs/issues", tasks=None):
    p = Path(directory) / f"{issue_id}-conclusion.md"
    if not p.exists():
        return [f"missing {p}: write the conclusion (templates/conclusion.md) before closing {issue_id}"]
    text = read_text(p)
    out = [f"{p}: section {h!r} missing" for h in CONCLUSION_HEADINGS if h not in text]
    o, rest = _answer_outcome(text)
    if not o or not re.search(r"\d", rest):
        out.append(f"{p}: the Answer needs 'Outcome: met' or 'Outcome: missed' with the measured number against the target")
    ip = issue_file(directory, issue_id)
    try:
        follows = load_spec(ip).get("follows") if ip else None
    except Exception:  # an unparseable header is reported by check()
        follows = None
    if follows and "## Hypotheses tested" not in text:
        out.append(f"{p}: section '## Hypotheses tested' missing (this issue follows {follows})")
    for tid, tp, ans in task_answers(issue_id, tasks or Path(directory).parent / "tasks"):
        if not ans or ans.startswith("<") or ans.startswith("At most 10 lines"):
            out.append(f"{tp}: task {tid} has no Answer")
    return out


def can_merge(issue_id, directory="docs/issues", tasks=None):
    """Why the issue's PR may not be merged yet (ADR-0023): closable, Outcome met, no task waiting for the person."""
    out = can_close(issue_id, directory, tasks)
    o = outcome(directory, issue_id)[0]
    if not out and o != "met":
        out.append(f"Outcome is {o}: do not merge; suggest /interview-failed-issue")
    tdir = Path(tasks or Path(directory).parent / "tasks")
    for p in sorted(tdir.glob("*.md")) if tdir.is_dir() else []:
        try:
            fm = yaml.safe_load(read_text(p).split("---", 2)[1]) or {}
        except (IndexError, yaml.YAMLError):
            continue
        if isinstance(fm, dict) and str(fm.get("issue")) == issue_id and fm.get("status") == "awaiting-approval":
            out.append(f"task {fm.get('id') or p.stem} awaits approval")
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["title", "label", "summary", "check", "task", "answers", "history", "can-close", "can-merge"])
    ap.add_argument("args", nargs="+")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--dir", default="docs/issues")
    ap.add_argument("--tasks", default="docs/tasks")
    ap.add_argument("--builds-on", help="task id of the previous slice this one extends (task command)")
    a = ap.parse_args(argv)
    if a.cmd == "title":
        print(task_title(a.args[0], a.args[1], " ".join(a.args[2:])))
        return 0
    if a.cmd == "label":
        print(label(a.args[0]))
        return 0
    if a.cmd == "check":
        fails, warns = check(a.args[0])
        for m in fails:
            print("FAIL:", m)
        for m in warns:
            print("WARN (add to Open items):", m)
        return 1 if fails else 0
    if a.cmd == "task":
        spec = load_spec(a.args[0])
        prev = next((ans for tid, _, ans in task_answers(spec["id"], a.tasks) if tid == a.builds_on), "")
        text = task_text(spec, a.args[1], " ".join(a.args[2:]), a.builds_on, prev)
        if not a.write:
            print(text)
            return 0
        slug = re.sub(r"[^a-z0-9]+", "-", " ".join(a.args[2:]).lower()).strip("-")
        out = Path(a.tasks) / f"{a.args[1]}-{slug}.md"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"{out}: task written")
        return 0
    if a.cmd == "history":
        ip = issue_file(a.dir, a.args[0])
        print((history_block(load_spec(ip), a.dir) if ip else "") or "no earlier attempts")
        return 0
    if a.cmd == "answers":
        for tid, _, ans in task_answers(a.args[0], Path(a.dir).parent / "tasks"):
            print(f"### {tid}\n{ans or '(no Answer yet)'}\n")
        return 0
    if a.cmd == "can-close":
        problems = can_close(a.args[0], a.dir)
        for m in problems:
            print("BLOCKED:", m)
        return 1 if problems else 0
    if a.cmd == "can-merge":
        problems = can_merge(a.args[0], a.dir)
        for m in problems:
            print("NOT MERGEABLE:", m)
        return 1 if problems else 0
    path = Path(a.args[0])
    block = summary_block(load_spec(path), path.parent)
    if not (a.write or a.check):
        print(block)
        return 0
    new = _replace(read_text(path), block)
    if new is None:
        print(f"{path}: no summary markers; add the 'At a glance' section from templates/issue.md")
        return 2
    if a.check:
        stale = new != read_text(path)
        print("summary block is stale: run with --write" if stale else "summary block is current")
        return 1 if stale else 0
    path.write_text(new, encoding="utf-8")
    print(f"{path}: summary block written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
